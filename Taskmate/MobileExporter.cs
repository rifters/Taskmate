            html.AppendLine("    </div>");
            
            // Assignments
            foreach (var assignment in assignments.OrderBy(a => a.Person))
            {
                var tasks = assignment.Tasks.Split(new[] { ", " }, StringSplitOptions.RemoveEmptyEntries);
                
                html.AppendLine("    <div class='person-card'>");
                html.AppendLine("        <div class='person-name'>");
