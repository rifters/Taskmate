                html.AppendLine($"            <span class='task-count'>{assignment.TaskCount} tasks</span>");
                html.AppendLine("        </div>");
                html.AppendLine("        <ul class='task-list'>");
                
                foreach (var task in tasks)
                {
                    html.AppendLine($"            <li class='task-item'>{task.Trim()}</li>");
                }
                
                html.AppendLine("        </ul>");
                html.AppendLine("    </div>");
            }
            
            // Footer
            html.AppendLine("    <div class='footer'>");
            html.AppendLine("        <p>Generated by Task Assigner</p>");
            html.AppendLine("        <p>© 2026 Task Assigner</p>");
            html.AppendLine("    </div>");
            html.AppendLine("</body>");
            html.AppendLine("</html>");
            
            return html.ToString();
        }

        public static string GenerateQRCode(string url, string outputPath)
        {
            try
            {
                using (QRCodeGenerator qrGenerator = new QRCodeGenerator())
                using (QRCodeData qrCodeData = qrGenerator.CreateQrCode(url, QRCodeGenerator.ECCLevel.Q))
                using (QRCode qrCode = new QRCode(qrCodeData))
                using (Bitmap qrCodeImage = qrCode.GetGraphic(20))
                {
                    qrCodeImage.Save(outputPath, ImageFormat.Png);
                    return outputPath;
                }
            }
            catch (Exception ex)
            {
                throw new Exception($"Failed to generate QR code: {ex.Message}");
            }
        }

        public static string SaveMobileExport(List<AssignmentResult> assignments, string title, string folderPath)
        {
            try
            {
                // Create folder if needed
                Directory.CreateDirectory(folderPath);
                
                // Generate HTML
                string htmlContent = GenerateMobileHTML(assignments, title);
                string htmlFileName = $"assignments_{DateTime.Now:yyyyMMdd_HHmmss}.html";
                string htmlPath = Path.Combine(folderPath, htmlFileName);
                File.WriteAllText(htmlPath, htmlContent);
                
                // Generate QR code pointing to the HTML file
                string qrFileName = $"qr_{DateTime.Now:yyyyMMdd_HHmmss}.png";
                string qrPath = Path.Combine(folderPath, qrFileName);
                GenerateQRCode($"file:///{htmlPath.Replace("\\", "/")}", qrPath);
                
                return htmlPath;
            }
            catch (Exception ex)
            {
                throw new Exception($"Failed to save mobile export: {ex.Message}");
            }
        }
